#!/usr/bin/env python3
"""Generates engine/Timetables.kt from transit_data.json. Run from repo root."""
import json, os, textwrap

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, "transit_data.json"), encoding="utf-8"))
out = os.path.join(root, "app/src/main/java/com/ozai/kampus/engine/Timetables.kt")

def strlit(tokens):
    body = " ".join(tokens)
    lines = textwrap.wrap(body, 100)
    return '"""\n        ' + "\n        ".join(lines) + '\n    """.trimIndent()'

def hm(h, m):
    return f"{h:02d}:{m:02d}"

# Weekend 130: all departures at bridge (per SPEC)
wk = ["06:35", "06:50", "07:05", "07:20", "07:35", "07:50", "08:05", "08:20", "08:30", "08:40", "08:50"]
mins = 9 * 60
while mins <= 23 * 60 + 30:
    wk.append(hm(mins // 60, mins % 60)); mins += 10
wk += ["23:40", "00:10", "00:40"]

ank = d["ankaray_dikimevi_to_asti"]
m2 = d["m2_koru_yonu_kizilay_aralik"]
r130 = [x["t"] + (x["tag"] or "") for x in d["r130"]["hafta_ici"]]

def m2kt(key):
    return "listOf(" + ", ".join(f'Triple("{a}", "{b}", {float(c)})' for a, b, c in m2[key]) + ")"

kt = f'''// GENERATED by tools/gen_timetables.py from transit_data.json - do not edit by hand.
package com.ozai.kampus.engine

/** Raw timetable data. Times after midnight (00:00-02:59) belong to the previous service day. */
object Timetables {{
    private fun split(s: String) = s.trim().split(Regex("\\\\s+"))

    /** Ankaray Dikimevi -> AŞTİ departures ("HH:MM"). */
    val ankaray: Map<DayType, List<String>> = mapOf(
        DayType.WEEKDAY to split({strlit(ank["hafta_ici"])}),
        DayType.SATURDAY to split({strlit(ank["cumartesi"])}),
        DayType.SUNDAY to split({strlit(ank["pazar"])})
    )

    /** M2 Koru yönü Kızılay headway intervals: (start, end, headwayMin). End "01:00" = after midnight. */
    val m2Headway: Map<DayType, List<Triple<String, String, Double>>> = mapOf(
        DayType.WEEKDAY to {m2kt("hafta_ici")},
        DayType.SATURDAY to {m2kt("cumartesi")},
        DayType.SUNDAY to {m2kt("pazar")}
    )
    const val M2_FIRST = "{m2["ilk"]}"
    const val M2_LAST = "{m2["son"]}"

    /** 130 weekday timetable: "HH:MM" followed by optional tag (K, B, D, Ü, ÜK). */
    val bus130Weekday: List<String> = split({strlit(r130)})

    /** 130 Saturday+Sunday departures, all at the bridge stop (10620). */
    val bus130WeekendBridge: List<String> = split({strlit(wk)})
}}
'''
open(out, "w", encoding="utf-8").write(kt)
print("wrote", out, len(ank["hafta_ici"]), len(r130), len(wk))
